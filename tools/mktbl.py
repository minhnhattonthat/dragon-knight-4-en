"""Write tbl/jp.tbl (Thingy format for $SKILL/scripts/tbl.py and jp_left.py) from tbl/glyphs_jp.txt."""
import os
from dk4 import ROOT, load_glyphs

g = load_glyphs()
lines = ['# generated by tools/mktbl.py from tbl/glyphs_jp.txt', '00={nl}', '11={sp}']
for code in sorted(g):
    key = '%02X' % code if code < 0x100 else '%04X' % code
    lines.append('%s=%s' % (key, g[code].rstrip('*') if False else g[code]))
open(os.path.join(ROOT, 'tbl', 'jp.tbl'), 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
print(len(lines))
