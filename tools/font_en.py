    for ch in sorted(G):
        assert len(set(len(r) for r in G[ch][0] + (G[ch][1] or []))) == 1, ch
        assert len(G[ch][0]) == 9 and (G[ch][1] is None or len(G[ch][1]) == 3), ch
    missing = [chr(c) for c in range(FIRST, LAST + 1) if chr(c) not in G]
    print('glyphs', len(G), 'missing', missing)
