# 0x7F is not a glyph: it is the "flush" code (a cell that only carries the previous letter's overflow).


def glyph(ch):
    """Return (rows[14] as 16-bit ints with bit 15 = leftmost hi-res px, advance width in hi-res px)."""
    body, desc = G[ch]
    w = max(len(r) for r in body)
    rows = [0] * 14
    for i, r in enumerate(body + (desc or [])):
        v = 0
        for x, c in enumerate(r):
            if c == '#':
                v |= 0b11 << (14 - 2 * x)
        rows[2 + i] = v
    return rows, 2 * w + GAP


def widths():
    return {ch: glyph(ch)[1] for ch in G}


